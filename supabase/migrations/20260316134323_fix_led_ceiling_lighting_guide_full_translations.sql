### Розрахунок блоку живлення

**Метод розрахунку:**
1. Визначте загальну довжину стрічки
2. Помножте на Вт/м
3. Додайте запас 20–30%
4. Округліть до наступного стандартного значення

**Приклад:**
- 15 м стрічки по 14 Вт/м = 210 Вт
- З запасом: 210 × 1,25 = 262 Вт
- Вибір: блок 300 Вт

### Вибір напруги

**12В vs 24В:**

**12В (найпоширеніший):**
- Широкий вибір компонентів
- Нижча вартість
- Для ділянок до 5 м
- Стандарт для житла

**24В (профільний вибір):**
- Менше падіння напруги
- Для довгих ділянок (10 м+)
- Вища ефективність

### Вибір перерізу проводу

- До 3 м: 0,5 мм²
- 3–7 м: 0,75 мм²
- 7–15 м: 1,0 мм²
- Більше 15 м: 1,5 мм²

