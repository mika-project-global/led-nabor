### Розрахунок світлових вимог

**Базова формула:**
Загальні люмени = Площа кімнати (м²) × Стандарт освітленості (люкс)

**Рекомендовані стандарти:**
- Спальня: 100-200 люкс
- Вітальня: 150-300 люкс
- Кухня: 200-400 люкс
- Ванна: 200-300 люкс
- Домашній офіс: 300-500 люкс
- Коридор: 100-150 люкс

**Приклад розрахунку:**
- Вітальня: 20 м²
- Стандарт: 200 люкс
- Потрібно загалом: 20 × 200 = 4000 люменів
- LED стрічка (16м периметр): 4000 ÷ 16 = 250 лм/м
- Обираємо: стрічку 600 лм/м з димером для гнучкості

### Вибір кольорової температури

**Стандартні рекомендації:**
- Спальні: 2700-3000K (тепле, розслаблююче)
- Житлові зони: 3000-4000K (нейтральне, універсальне)
- Кухні: 4000-5000K (холодне, функціональне)
- Ванні: 4000-4500K (нейтральне, чисте)
