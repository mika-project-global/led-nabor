## Методи установки

### Периметральне освітлення стелі

**Найпопулярніша техніка для житла:**
- LED стрічки по периметру кімнати
- Створює ефект плаваючої стелі
- Непряме навколишнє освітлення
- Сучасна чиста естетика

**Кроки установки:**
1. Сплануйте розміщення стрічки (10-15см від стіни)
2. Встановіть монтажний виступ або профіль
3. Проведіть електрику до початкової точки
4. Встановіть та підключіть LED стрічки
5. Встановіть блок живлення (приховане місце)
6. Підключіть контролер/димер
7. Ретельно протестуйте

