## Sicherheitsaspekte

### Brandschutz

**Kritische Punkte:**
- LED-Streifen niemals mit Bettzeug, Kissen oder Stoff abdecken
- Ausreichende Belueftung um das Netzteil sicherstellen
- Keine Kabel unter der Matratze verlegen
- Nur hochwertige zertifizierte Netzteile verwenden
- Kontakt mit ueberhitzungsgefaehrdeten Materialien vermeiden
- Alle Verbindungen sicher befestigen
- In den ersten Tagen auf Ueberhitzung pruefen

### Kindersicherheit

**Fuer Kinderschlafzimmer:**
- Alle Kabel und Netzteile ausser Reichweite sichern
- LED-Streifen mit IP-Schutzklasse (versiegelt) verwenden
- Niederspannung (12V/24V) minimiert Stromschlagrisiko
- Kindern beibringen, die Verkabelung nicht zu beruehren
- Batteriebetrieb fuer sehr kleine Kinder erwaegen
- Keine kleinen abnehmbaren Teile
- Bewegungssensoren vermeiden Wandschalter

### Bedenken bezueglich elektromagnetischer Felder (EMF)

**Minimierung der Exposition:**
- LED-Streifen emittieren minimale EMF
- Netzteil 2+ Meter vom Kopfende des Bettes entfernt halten
- DC-Stromversorgung (12V/24V) sicherer als AC
- Bei Bedenken abgeschirmte Kabel verwenden
- Keine wissenschaftlich nachgewiesenen Gesundheitsrisiken bei normalen Werten
- Hochwertige Netzteile haben bessere Abschirmung

