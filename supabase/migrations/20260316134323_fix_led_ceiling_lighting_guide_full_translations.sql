### Розрахунок потреб у світлі

**Базова формула:**
Загальний лімен = Площа кімнати (м²) × Норма освітленості (люкс)

**Рекомендовані норми:**
- Спальня: 100–200 люкс
- Вітальня: 150–300 люкс
