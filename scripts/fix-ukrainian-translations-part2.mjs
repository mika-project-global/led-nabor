// Read the uk.json file
const ukJsonPath = join(__dirname, '..', 'src', 'i18n', 'locales', 'uk.json');
let content = fs.readFileSync(ukJsonPath, 'utf8');

// Track changes
let changesCount = 0;

// Apply all translations
for (const [russian, ukrainian] of Object.entries(translations)) {
  const before = content;
  content = content.replace(new RegExp(russian.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'), ukrainian);
  if (before !== content) {
    changesCount++;
    console.log(`✓ Replaced: "${russian.substring(0, 50)}${russian.length > 50 ? '...' : ''}"`);
  }
}

// Write back the file
fs.writeFileSync(ukJsonPath, content, 'utf8');

console.log(`\n✅ Done! Made ${changesCount} replacements in uk.json`);
