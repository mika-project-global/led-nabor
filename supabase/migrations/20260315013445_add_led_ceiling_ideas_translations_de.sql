## Wartung und Langlebigkeit

### Regelmaessige Pflege

**Monatlich:**
- Aluminiumprofile und Diffusoren abstauben
- Auf lose Abschnitte pruefen
- Alle Zonen und Steuerungen testen
- Mit weichem, trockenem Tuch abwischen

**Vierteljaehrlich:**
- Tiefenreinigung aller sichtbaren Komponenten
- Elektrische Verbindungen inspizieren
- Notfallszenarien testen
- Smart-Controller-Firmware aktualisieren

**Jaehrlich:**
- Komplette Systempruefung
- Alle Befestigungen auf Sicherheit pruefen
- Netzteile auf Probleme pruefen
- Hinzufuegen neuer Features/Zonen erwaegen

### Erwartete Lebensdauer

**LED-Streifen:**
- Qualitaetsstreifen: 15-20 Jahre typische Nutzung
- Budget-Streifen: 5-10 Jahre
- Allmaehlicher Helligkeitsabfall (30% ueber Lebensdauer)
- Normalerweise lohnt es sich, alle auf einmal zu ersetzen

**Controller und Netzteile:**
- Budget: 2-5 Jahre
- Qualitaet: 7-10 Jahre
- Normalerweise zuerst zu ersetzen
- Einfach und erschwinglich aufzuruesten

**Aluminiumprofile:**
- Im Wesentlichen permanent
- Keine Degradation
- Wiederverwendbar beim LED-Upgrade
- Einmalige Investition

## Behebung haeufiger Probleme

**Problem: Ungleichmaessige Helligkeit entlang des Streifens**
- **Loesung:** Stromeinspeisung alle 5 Meter hinzufuegen
- Alle Verbindungen auf Korrosion pruefen
- Adaequaten Kabelquerschnitt ueberpruefen
- Parallelverkabelung fuer lange Laeufe erwaegen

**Problem: Farben stimmen nicht zwischen Streifen ueberein**
- **Loesung:** LEDs aus gleicher Charge/Hersteller verwenden
- RGB-Controller kalibrieren
- LED-Bin-Nummern abgleichen
- Gewisse Variation als normal akzeptieren

**Problem: Flackern**
- **Loesung:** Nur LED-kompatible Dimmer verwenden
- Netzteil-Qualitaet und -Kapazitaet pruefen
- Alle Verbindungen auf festen Sitz pruefen
- Moegerweise anderen Controller-Typ benoetigt

**Problem: Unzuverlaessige Smart-Steuerung**
- **Loesung:** WiFi-Abdeckung verbessern
- Hub-basiertes System erwaegen
- Firmware aktualisieren
- Netzteilstabilitaet pruefen

